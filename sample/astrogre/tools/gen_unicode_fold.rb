#!/usr/bin/env ruby
# frozen_string_literal: true
#
# Simple case folding for /i on non-ASCII characters.
#
#   ruby tools/gen_unicode_fold.rb > unicode_fold.h
#
# Like gen_unicode_tables.rb the source is the host CRuby: each codepoint's
# String#downcase(:fold), kept when it is a single codepoint (multi-codepoint
# folds such as ß → ss are not represented).  ASCII-to-ASCII pairs are left
# out; the matcher's byte compare already folds those.

pairs = []
(0x80..0x10FFFF).each do |c|
  next if c.between?(0xD800, 0xDFFF)
  s = [c].pack("U")
  f = s.downcase(:fold)
  if f.length != 1   # a full fold to several codepoints: keep the simple one CRuby's /i agrees with (ẞ → ß)
    d = s.downcase
    f = d if d.length == 1 && d != s && Regexp.new("\\A#{Regexp.escape(d)}\\z", Regexp::IGNORECASE).match?(s)
  end
  next if f == s || f.length != 1
  pairs << [c, f.ord]
end
# a fold target in the ASCII range reached from a non-ASCII codepoint (K → k)
# is covered by the pair itself; no extra rows needed.

puts "/* Generated by tools/gen_unicode_fold.rb from #{RUBY_DESCRIPTION.split.first(2).join(' ')} — do not edit. */"
puts "/* {codepoint, its simple case fold}, sorted by codepoint. */"
puts "static const struct { uint32_t cp, fold; } agre_fold_tab[] = {"
pairs.each_slice(4) { |sl| puts "    " + sl.map { |c, f| format("{ 0x%04X, 0x%04X }", c, f) }.join(", ") + "," }
puts "};"
puts "#define AGRE_FOLD_N (sizeof agre_fold_tab / sizeof agre_fold_tab[0])"
