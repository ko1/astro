# -0.0 と Infinity のリテラル。AOT の SD は double オペランドを C のソース
# リテラルとして焼くので、"%.17g" だけだと "-0" が整数トークンになって符号が
# 落ち、"inf" はそもそも C として不正だった (astro_fprint_double)。
p(-0.0)
p((-0.0).to_s)
p((-0.0).arg)
p((0.0).arg)
p(1.0 / -0.0)
p(-0.0 == 0.0)
p [-0.0].inspect
p(-0.0 <=> 0.0)
p Math.atan2(-0.0, -1.0)
p(("%e" % 1e1020))
p(("%f" % -1e1020))
p(1e1020)
p(-1e1020)
p(1e1020 - 1e1020)
p(3.0)
p(-3.0)
p(1.5e-300)
