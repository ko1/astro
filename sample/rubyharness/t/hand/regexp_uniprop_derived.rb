# 派生 Unicode プロパティ (rouge の lexer が XID_Start/XID_Continue を使う)
p("aB_9é" =~ /\A[\p{XID_Start}_]\p{XID_Continue}*\z/)
p("1abc" =~ /\A\p{XID_Start}/)
p("x" =~ /\p{Emoji}/, "🎉" =~ /\p{Emoji}/)
p("a" =~ /\p{Math}/, "+" =~ /\p{Math}/)
p("f" =~ /\p{Hex_Digit}/, "g" =~ /\p{Hex_Digit}/)
p("-" =~ /\p{Dash}/, "a" =~ /\p{Dash}/)
p("­" =~ /\p{Default_Ignorable_Code_Point}/)
p("é".unicode_normalize(:nfd) =~ /\p{Grapheme_Extend}/)
p("漢" =~ /\p{Ideographic}/, "a" =~ /\p{Ideographic}/)
p("\"" =~ /\p{Quotation_Mark}/)
p("A" =~ /\p{Cased}/, "1" =~ /\p{Cased}/)
p "a1_é漢".scan(/\p{XID_Continue}/)
