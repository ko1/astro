# 重複した名前の扱いは flat とデストラクチャで違う (CRuby):
#   flat |_, _|       → 最初の出現が残る (代入は 1 回だけ)
#   destr |(_, _)|    → 多重代入なので左から順に書き、最後が残る
p proc { |_, _| _ }.call(1, 2)
p proc { |(_, _)| _ }.call([1, 2])
p proc { |_, _, _| _ }.call(1, 2, 3)
p proc { |(_, _, _)| _ }.call([1, 2, 3])
p proc { |a, _, _| [a, _] }.call(1, 2, 3)
p [[1,2,3]].map { |(a, _, _)| a }
p [[1,2,3]].map { |(_, b, _)| b }
p [[1,2,3]].map { |(_, _, c)| c }
p({ a: 1 }.map { |(k, _)| k })
p [[1,[2,3]]].map { |(a, (_, _))| a }
p [[1,[2,3]]].map { |(_, (_, x))| x }
p [[1,2],[3,4]].each_with_index.map { |(a, _), i| [a, i] }
p [[1,2,3,4]].map { |(a, *_, d)| [a, d] }
