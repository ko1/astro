# Generate builtins/reflect_owner.h: the methods koruby defines directly on a core
# class that CRuby owns in an ancestor (Comparable#clamp on Integer, the Enumerable
# methods on Array/Hash/Range, ...).  Reflection (instance_methods(false),
# Method#owner) reports CRuby's owner for them.
#   ruby tools/gen_reflect_owner.rb KORUBY CRUBY > builtins/reflect_owner.h
require "json"
koruby, cruby = ARGV
abort "usage: gen_reflect_owner.rb KORUBY CRUBY" unless koruby && cruby
CLASSES = %w[Integer Float Numeric String Symbol Array Hash Range Proc Method UnboundMethod
             Regexp MatchData Time Struct Exception NilClass TrueClass FalseClass Rational
             Complex Enumerator IO File Dir Set Thread Fiber Module Class Object Encoding Random]
dump = <<~RUBY
  require "json"
  out = {}
  #{CLASSES.inspect}.each do |n|
    k = Object.const_get(n) rescue next
    out[n] = (k.instance_methods(false) + k.private_instance_methods(false)).map(&:to_s).sort
  end
  print JSON.generate(out)
RUBY
kor = JSON.parse(IO.popen({ "KORB_REFLECT_RAW" => "1" }, [koruby, "-e", dump], &:read))   # koruby's own tables, unmapped
cru = JSON.parse(IO.popen([cruby, "-e", dump], &:read))
rows = []
CLASSES.each do |n|
  next unless kor[n] && cru[n]
  (kor[n] - cru[n]).each { |m| rows << [n, m] }
end
# ask CRuby who owns each extra (nil: CRuby has no such method on the class at all)
query = "require 'json'; rows = #{JSON.generate(rows)}; print JSON.generate(rows.map { |n, m| k = Object.const_get(n); o = (k.instance_method(m).owner rescue nil); o && o.name })"
own = JSON.parse(IO.popen([cruby, "-e", query], &:read))
puts "/* Generated by tools/gen_reflect_owner.rb — do not edit. */"
puts "/* {class, method, CRuby's owner} for methods koruby defines on the class itself. */"
puts "static const struct { const char *klass, *mid, *owner; } korb_reflect_owner_tab[] = {"
rows.zip(own).each do |(n, m), o|
  next if o.nil? || o == n
  puts %(    { "#{n}", #{m.dump}, "#{o}" },)
end
puts "};"
