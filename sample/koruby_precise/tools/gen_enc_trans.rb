# Generate builtins/enc_trans.h: CRuby's (Onigmo's) byte-structure state tables
# for the multi-byte encodings, so String#valid_encoding? / #scrub judge a byte
# sequence the way CRuby does (structure, not whether it maps to Unicode).
#   ruby tools/gen_enc_trans.rb ~/ruby/src/master/enc > builtins/enc_trans.h
dir = ARGV[0] or abort "usage: gen_enc_trans.rb CRUBY_SRC/enc"
# file => encoding names that use its table (CRuby replicas / aliases)
FILES = {
  "euc_jp"     => %w[EUC-JP eucJP eucJP-ms euc-jp-ms CP51932 EUC-JIS-2004 EUC-JISX0213],
  "emacs_mule" => %w[Emacs-Mule stateless-ISO-2022-JP],
  "gb18030"    => %w[GB18030],
  "big5"       => %w[Big5 Big5-HKSCS Big5-UAO CP950 CP951],
  "gbk"        => %w[GBK CP936],
  "euc_kr"     => %w[EUC-KR eucKR],
  "cp949"      => %w[CP949],
  "euc_tw"     => %w[EUC-TW eucTW],
  # Windows-31J and the carrier variants share Shift_JIS's structure (shift_jis.h)
  "shift_jis"  => %w[Shift_JIS Windows-31J SJIS CP932 csWindows31J PCK MacJapanese MacJapan
                     SJIS-DoCoMo SJIS-KDDI SJIS-SoftBank],
}
out = +"/* Generated by tools/gen_enc_trans.rb from CRuby enc/<name>.c; do not edit.\n" \
       " * trans[state][byte]: >= 0 next state, -1 ACCEPT (character complete),\n" \
       " * -2 FAILURE (invalid).  Every table starts in state 0. */\n"
names = []
FILES.each do |base, encs|
  path = File.join(dir, "#{base}.c")
  path = File.join(dir, "#{base}.h") unless File.read(path).include?("trans[][0x100]")   # shift_jis.c keeps it in its .h
  src = File.read(path)
  body = src[/static const signed char trans\[\]\[0x100\] = \{(.*?)\n\};/m, 1] or abort "no trans in #{base}"
  body = body.gsub(%r{/\*.*?\*/}m, "")
  rows = body.scan(/\{([^{}]*)\}/).map do |(r)|
    r.split(",").map(&:strip).reject(&:empty?).map do |t|
      case t
      when "A" then -1
      when "F" then -2
      when /\AS(\d+)\z/ then $1.to_i
      else Integer(t)
      end
    end
  end
  rows.each { |r| abort "#{base}: row of #{r.size}" unless r.size == 256 }
  out << "static const signed char korb_enc_trans_#{base}[#{rows.size}][256] = {\n"
  rows.each { |r| out << "  {" << r.join(",") << "},\n" }
  out << "};\n"
  encs.each { |e| names << [e, base] }
end
out << "static const struct { const char *name; const signed char (*trans)[256]; } korb_enc_trans_tab[] = {\n"
names.each { |e, b| out << "  { \"#{e}\", korb_enc_trans_#{b} },\n" }
out << "};\n"
print out
