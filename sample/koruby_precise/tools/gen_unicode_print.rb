# Generate builtins/unicode_print.h: the codepoints Onigmo calls printable
# (CR_Print, what [[:print:]] and String#inspect use), from astrogre's tables.
#   ruby tools/gen_unicode_print.rb ../astrogre/unicode_tables.c > builtins/unicode_print.h
src = File.read(ARGV[0] || abort("usage: gen_unicode_print.rb unicode_tables.c"))
pool_src = src[/agre_uni_pool\[\] = \{(.*?)\n\};/m, 1] or abort "no pool"
pool = pool_src.scan(/\{0x(\h+),0x(\h+)\}/).map { |a, b| [a.hex, b.hex] }
off, len = src[/\{"print",\s*(\d+),\s*(\d+)\}/, 0] && [$1.to_i, $2.to_i]
abort "no print property" unless off
ranges = pool[off, len]
abort "short pool" unless ranges.size == len
out = +"/* Generated by tools/gen_unicode_print.rb from astrogre's Unicode tables; do not edit.\n" \
       " * Onigmo's CR_Print as sorted, disjoint ranges. */\n"
out << "static const uint32_t korb_uc_print[#{ranges.size}][2] = {\n"
ranges.each_slice(4) { |sl| out << "  " << sl.map { |a, b| format("{0x%X,0x%X}", a, b) }.join(", ") << ",\n" }
out << "};\n"
print out
